import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const sourcePath = resolve("skills/plan-local-trip/references/planning-core.md");
const outputPath = process.env.SENDERO_PLANNING_PROTOCOL_OUTPUT_PATH
  ? resolve(process.env.SENDERO_PLANNING_PROTOCOL_OUTPUT_PATH)
  : resolve("server/generated/planning-protocol.mjs");
const source = await readFile(sourcePath, "utf8");
const match = source.match(/^---\r?\nprotocolVersion:\s*([^\r\n]+)\r?\n---\r?\n([\s\S]*)$/);

if (!match) {
  throw new Error("planning-core.md must start with a protocolVersion frontmatter field");
}

const protocolVersion = match[1].trim();
if (!/^\d+\.\d+\.\d+$/.test(protocolVersion)) {
  throw new Error("planning-core.md protocolVersion must use semantic versioning");
}

const instructions = match[2].trim();
const generated = [
  "// Generated by npm run build:planning-protocol. Edit planning-core.md instead.",
  `export const planningProtocolVersion = ${JSON.stringify(protocolVersion)};`,
  `export const planningInstructions = ${JSON.stringify(instructions)};`,
  "",
].join("\n");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
console.log(`Built Sendero planning protocol ${protocolVersion}.`);
